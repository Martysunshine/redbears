_BY_ID = {p.id: p for p in PROFILES}


def all_profiles() -> list[ConnectorProfile]:
    return list(PROFILES)


def get_profile(connector_id: str) -> ConnectorProfile | None:
    return _BY_ID.get(connector_id)


def build_connector(profile: ConnectorProfile) -> SourceConnector:
    """Instantiate the right connector implementation for a profile."""
    if profile.source_type == SourceType.GIT:
        return GitConnector(profile)
    if profile.source_type == SourceType.JSON_STIX:
        return StixConnector(profile)
    if profile.source_type == SourceType.API and profile.id == "mitre-d3fend-src":
        return D3fendConnector(profile)
    if profile.source_type == SourceType.PDF:
        return PdfConnector(profile)
    if profile.source_type == SourceType.RFC:
        return RfcConnector(profile)
    # Other source types (archive/generic api) are defined but not yet implemented.
    raise NotImplementedError(f"source_type '{profile.source_type}' not yet supported")


def get_connector(connector_id: str) -> SourceConnector | None:
    p = get_profile(connector_id)
    if p is None:
        return None
    return build_connector(p)
